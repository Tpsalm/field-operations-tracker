export interface VsrAuditKPIs {
  totalAudited: number;
  inStoreCount: number;
  inStorePct: number;
  outOfBoundsCount: number;
  perimeterCount: number;
  onTimeSignInCount: number;
  onTimeSignInPct: number;
  closingCompliantCount: number;
  closingCompliantPct: number;
  flaggedCount: number;
  pendingReviewCount: number;
  activeOnShiftCount: number;
  avgDurationHours: number;
}

export function computeVsrAuditKPIs(records: VsrLocationAuditRecord[]): VsrAuditKPIs {
  const totalAudited = records.length;
  if (totalAudited === 0) {
    return {
      totalAudited: 0,
      inStoreCount: 0,
      inStorePct: 0,
      outOfBoundsCount: 0,
      perimeterCount: 0,
      onTimeSignInCount: 0,
      onTimeSignInPct: 0,
      closingCompliantCount: 0,
      closingCompliantPct: 0,
      flaggedCount: 0,
      pendingReviewCount: 0,
      activeOnShiftCount: 0,
      avgDurationHours: 0
    };
  }

  const inStoreCount = records.filter((r) => r.signInGeofenceStatus === 'in_store').length;
  const outOfBoundsCount = records.filter((r) => r.signInGeofenceStatus === 'out_of_bounds').length;
  const perimeterCount = records.filter((r) => r.signInGeofenceStatus === 'near_store').length;
  const onTimeSignInCount = records.filter((r) => r.signInOnTimeStatus === 'on_time').length;
  const closingCompliantCount = records.filter(
    (r) => r.closingComplianceStatus === 'on_time_signout'
  ).length;
  const flaggedCount = records.filter((r) => r.auditStatus === 'flagged').length;
  const pendingReviewCount = records.filter((r) => r.auditStatus === 'pending_review').length;
  const activeOnShiftCount = records.filter((r) => r.signOutTimeWat === null).length;

  const totalDecimal = records.reduce((acc, r) => acc + r.totalHoursDecimal, 0);
  const avgDurationHours = parseFloat((totalDecimal / totalAudited).toFixed(1));

  return {
    totalAudited,
    inStoreCount,
    inStorePct: parseFloat(((inStoreCount / totalAudited) * 100).toFixed(1)),
    outOfBoundsCount,
    perimeterCount,
    onTimeSignInCount,
    onTimeSignInPct: parseFloat(((onTimeSignInCount / totalAudited) * 100).toFixed(1)),
    closingCompliantCount,
    closingCompliantPct: parseFloat(((closingCompliantCount / totalAudited) * 100).toFixed(1)),
    flaggedCount,
    pendingReviewCount,
    activeOnShiftCount,
    avgDurationHours
  };
}
